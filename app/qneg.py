# -*- coding: utf-8 -*-
"""Вопросы и отрицания: «Бу песиме?» / «Бу песи түгел».

Формы строятся здесь ОДНОЙ функцией и для движка уроков, и для скрипта
предозвучки (tools/gen_qneg_tts.py) — кэш TTS ищется по точной строке.

Частица -мы/-ме — по сингармонизму (последняя гласная основы). Татарская «е»
коварна: в части слов она обозначает задний звук (сыер → сыермы), поэтому
исключения собраны экспертом в HARD_BACK/HARD_FRONT.
"""

BACK_VOWELS = set("аоуыёя")   # я/ё ~ [а]/[о]
FRONT_VOWELS = set("әөүеэи")

# Слова, где правило «по последней букве-гласной» даёт неверную частицу
# (проверено носителем 2026-07-17: «е»-задний звук, арабизмы, русизмы).
HARD_BACK = {"сыер", "муен", "каеш", "свитер", "пластилин", "котлет"}
HARD_FRONT = {"чия", "сәгать", "молния", "кәгазь", "фамилия"}

# Темы с конкретными существительными — только там вопрос «Бу X-мы?» осмыслен с картинкой
QUESTION_THEMES = {
    "Животные: дома и во дворе", "Животные: в лесу и зоопарке",
    "Фрукты/ягоды", "Овощи", "Птицы, рыбки, букашки",
    "Одежда и обувь", "Продукты и напитки", "Вещи в доме",
    "Пенал и рюкзак", "Лицо и голова", "Моё тело", "Блюда и вкусы",
}

# Исключения носителя: глагол в списке существительных, абстракции и неизобразимое
QNEG_EXCLUDE = {"эчә", "буй", "исем", "фамилия", "тавыш", "көлү",
                "сәламәтлек", "акыл", "көч", "кыргый"}


def qneg_eligible(text_tt: str) -> bool:
    """Слово годится для вопроса/отрицания: однословное и не из исключений."""
    w = text_tt.strip().lower()
    return " " not in w and "-" not in w and w not in QNEG_EXCLUDE


def question_particle(word_tt: str) -> str:
    w = word_tt.strip().lower()
    if w in HARD_BACK:
        return "мы"
    if w in HARD_FRONT:
        return "ме"
    for ch in reversed(w):
        if ch in BACK_VOWELS:
            return "мы"
        if ch in FRONT_VOWELS:
            return "ме"
    return "мы"


def question_word(word_tt: str) -> str:
    """песи → песиме (слово с вопросительной частицей, плитка конструктора)."""
    w = word_tt.strip().lower()
    return w + question_particle(w)


def question_phrase(word_tt: str) -> str:
    """Полная фраза вопроса: «Бу песиме?»"""
    return f"Бу {question_word(word_tt)}?"


def negation_phrase(word_tt: str) -> str:
    """Полная фраза отрицания: «Бу песи түгел.»"""
    return f"Бу {word_tt.strip().lower()} түгел."


