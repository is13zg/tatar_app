# -*- coding: utf-8 -*-
"""Перестройка вежливых тем (2026-08-15, план утверждён владельцем).

Было три перемешанных темы: прощания жили в трёх местах, пара «гафу ит /
гафу итегез» была разнесена на 25 юнитов, «әйе/юк» числились вежливостью.
Стало три уровня по частотности (по итогам разбора курса «Мин татар»,
словарика и книги «Сүзләр дөньясы» + план методиста-носителя):

  3.  «Привет, пока, спасибо» — ядро первых недель, ты/вы-пары рядом;
  15. «Волшебные слова» — диалоги: просьба, мирилка, «как дела?»;
  22. «Добрые пожелания» — ситуативные формулы, темп 2 слова/урок.

Слова не удаляются — только переезжают (прогресс детей привязан к слову).
Уроки режутся по words.sort_order. Идемпотентно.

  python tools/restructure_polite.py [путь_к_БД]

После прогона: tools/reorder_units.py (позиция 22) и переозвучка новых слов.
"""
import sqlite3
import sys

DB = sys.argv[1] if len(sys.argv) > 1 else "app.db"

# старое имя -> (новое имя RU, новое имя TT, эмодзи, описание)
RENAMES = {
    "Привет и пока": ("Привет, пока, спасибо", "Исәнләшү", "👋",
                      "Ядро вежливости: привет/пока, спасибо, да/нет, ты- и вы-формы рядом"),
    "Вежливые слова": ("Волшебные слова", "Тылсымлы сүзләр", "🪄",
                       "Диалоги: просьба, мирилка «Гафу ит! — Зыян юк», «Хәлләр ничек?»"),
    "Вежливые фразы": ("Добрые пожелания", "Изге теләкләр", "🌟",
                       "Пожелания по ситуации: на ночь, чихнувшему, путнику, в праздник"),
}

# итоговый состав: тема -> [(text_tt, sort_order)] — sort_order режет уроки
# (обычный темп 4/урок, у «Добрых пожеланий» 2/урок)
COMPOSITION = {
    "Привет, пока, спасибо": [
        # урок 1: первые речевые кнопки
        ("сәлам", 10), ("сау бул", 20), ("әйе", 30), ("юк", 40),
        # урок 2: спасибо + ты/вы-пары
        ("рәхмәт", 50), ("исәнме", 60), ("исәнмесез", 70), ("сау булыгыз", 80),
        # урок 3: хәерле-тройка (решение владельца: рано, как в пособиях)
        ("хәерле иртә", 90), ("хәерле көн", 100), ("хәерле кич", 110),
    ],
    "Волшебные слова": [
        # урок 1 «Просьба»
        ("зинһар", 10), ("ярдәм ит", 20), ("рәхим ит", 30), ("Рәхим итегез!", 40),
        # урок 2 «Мирилка»
        ("Гафу ит!", 50), ("гафу итегез", 60), ("Ачуланма!", 70), ("зыян юк", 80),
        # урок 3 «Хәлләр ничек?»
        ("хәлләр ничек?", 90), ("әйбәт", 100), ("яхшы", 110), ("начар", 120),
    ],
    "Добрые пожелания": [
        # по два на урок: каждая пара — сценка
        ("Тыныч йокы!", 10), ("Тәмле төшләр!", 20),      # на ночь
        ("Сәламәт бул!", 30), ("зур үс", 40),            # пожелания-ответы
        ("тәбрик итәм", 50), ("туган көнең белән", 60),  # праздник
        ("Хәерле юл!", 70), ("Хуш!", 80),                # проводы
        ("бик шатмын", 90),                              # финал: «мин бик шатмын!»
    ],
}

# новые слова: text_tt -> (text_ru, emoji, sentence_tt, sentence_ru)
NEW_WORDS = {
    "исәнме": ("здравствуй", "👋",
               "— Исәнме, дустым! —", "— Здравствуй, дружок! —"),
    "рәхим ит": ("угощайся, проходи", "🤲",
                 "— Рәхим ит, дустым! —", "— Угощайся, дружок! —"),
    "зыян юк": ("ничего страшного", "🤗",
                "— Гафу ит! — Зыян юк! —", "— Извини! — Ничего страшного! —"),
    "әйбәт": ("отлично", "👍",
              "— Хәлләр ничек? — Әйбәт! —", "— Как дела? — Отлично! —"),
    "зур үс": ("расти большой", "🌱",
               "— Рәхмәт, әби! — Зур үс! —", "— Спасибо, бабушка! — Расти большой! —"),
    "туган көнең белән": ("с днём рождения", "🎂",
                          "— Туган көнең белән, дустым! —", "— С днём рождения, дружок! —"),
}


def main() -> None:
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row

    # 1. переименования тем (идемпотентно: ищем и старое имя, и новое)
    ids = {}
    for old, (new, tt, icon, desc) in RENAMES.items():
        row = con.execute("select id from themes where title_ru in (?, ?)", (old, new)).fetchone()
        if not row:
            sys.exit(f"тема «{old}»/«{new}» не найдена")
        con.execute("update themes set title_ru=?, title_tt=?, icon_emoji=?, description=? where id=?",
                    (new, tt, icon, desc, row["id"]))
        ids[new] = row["id"]

    # 2. состав: переносы, sort_order, добавки
    moved = added = 0
    for theme_new, words in COMPOSITION.items():
        tid = ids[theme_new]
        for tt_word, order in words:
            row = con.execute("select id, theme_id from words where lower(text_tt)=lower(?)",
                              (tt_word,)).fetchone()
            if row:
                if row["theme_id"] != tid:
                    moved += 1
                con.execute("update words set theme_id=?, sort_order=? where id=?",
                            (tid, order, row["id"]))
            else:
                ru, emoji, s_tt, s_ru = NEW_WORDS[tt_word]
                con.execute(
                    "insert into words (theme_id, text_tt, text_ru, emoji, sentence_tt, sentence_ru, sort_order)"
                    " values (?,?,?,?,?,?,?)",
                    (tid, tt_word, ru, emoji, s_tt, s_ru, order))
                added += 1
    con.commit()

    # 3. контроль: в трёх темах ровно задуманный состав
    for theme_new, words in COMPOSITION.items():
        have = [r["text_tt"] for r in con.execute(
            "select text_tt from words where theme_id=? order by sort_order, id", (ids[theme_new],))]
        want = [w for w, _o in words]
        extra = [w for w in have if w.lower() not in {x.lower() for x in want}]
        if extra:
            sys.exit(f"в «{theme_new}» лишние слова: {extra} — план не покрывает, останов")
        print(f"{theme_new}: {len(have)} слов — {', '.join(have)}")
    print(f"\nперенесено: {moved}, добавлено: {added}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
