def main() -> None:
    db_path = sys.argv[1] if len(sys.argv) > 1 else "app.db"
    con = sqlite3.connect(db_path)
    con.execute("PRAGMA foreign_keys=ON")
    cur = con.cursor()
    done = 0
    for tt_old, (ru_new, tt_new) in VERBS.items():
        cur.execute("update words set text_ru=?, text_tt=?, tts_url=NULL where text_tt=?", (ru_new, tt_new, tt_old))
        if cur.rowcount:
            done += cur.rowcount
        else:
            print(f"SKIP (нет): {tt_old}")
    con.commit()
    print(f"Обновлено глаголов: {done}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
