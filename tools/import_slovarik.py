def clean_variant(s: str) -> str:
    """Первый вариант из 'А / Б', без скобок, схлопнутые пробелы, нижний регистр."""
    s = s.split(" / ")[0]
    s = re.sub(r"\([^)]*\)", "", s)
    return " ".join(s.split()).strip(" .").lower()


def parse_pdf(pdf_path: str) -> dict[int, list[dict]]:
    reader = pypdf.PdfReader(pdf_path)
    full = "\n".join(p.extract_text() or "" for p in reader.pages)
    # убрать колонтитулы
    full = re.sub(r"Русско-татарский словарик · 1000 слов · 1 класс", " ", full)
    full = re.sub(r"стр\.\s*\d+", " ", full)

    # заголовки разделов: 'N. ЗАГОЛОВОК · татарча · X сл.'
    header_re = re.compile(r"(?m)^\s*(\d{1,2})\.\s+([А-ЯЁ][А-ЯЁA-Z ,/()0-9-]*?)\s*·")
    headers = [(int(m.group(1)), m.start()) for m in header_re.finditer(full)]
    sections: dict[int, list[dict]] = {}
    for i, (num, start) in enumerate(headers):
        end = headers[i + 1][1] if i + 1 < len(headers) else len(full)
        chunk = full[start:end]
        # отрезать строку заголовка (до 'X сл.')
        chunk = re.sub(r"^.*?·\s*\d+\s*сл\.?", "", chunk, count=1, flags=re.S)
        entries = []
        for m in re.finditer(r"(\d{1,4})\.\s*(.+?)\s*—\s*(.*?)(?=\s*\d{1,4}\.\s|\Z)", chunk, re.S):
            ru_raw = " ".join(m.group(2).split())
            tt_raw = " ".join(m.group(3).split())
            if not ru_raw or not tt_raw:
                continue
            entries.append({"n": int(m.group(1)), "ru_raw": ru_raw, "tt_raw": tt_raw})
        sections[num] = entries
    return sections


def build_units(sections: dict[int, list[dict]]) -> list[dict]:
    units = []
    for sec_num, meta in SECTIONS.items():
        entries = sections.get(sec_num, [])
        words = []
        for e in entries:
            text_ru = clean_variant(e["ru_raw"])
            text_tt = clean_variant(e["tt_raw"])
            if not text_ru or not text_tt:
                continue
            emoji = EMOJI.get(text_ru.lower()) or EMOJI.get(e["ru_raw"].lower()) or meta["icon"]
            words.append({"text_ru": text_ru, "text_tt": text_tt, "emoji": emoji})
        units.append({
            "title_ru": meta["title_ru"],
            "title_tt": meta["title_tt"],
            "icon_emoji": meta["icon"],
            "order_index": meta["order"],
            "words": words,
        })
    units.extend(EXISTING_THEMES)  # только порядок/иконки, без слов
    return units


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pdf", default="tatar_slovarik_1000 (1).pdf")
    ap.add_argument("--out", default="seed_words.json")
    ap.add_argument("--push", help="URL приложения, например http://127.0.0.1:8001")
    ap.add_argument("--user", default="admin")
    ap.add_argument("--password", default="")
    args = ap.parse_args()

    sections = parse_pdf(args.pdf)
    for num, entries in sorted(sections.items()):
        mark = "*" if num in SECTIONS else " "
        print(f"{mark} раздел {num}: {len(entries)} слов")

    units = build_units(sections)
    payload = {"units": units, "skip_existing_global": True}
    Path(args.out).write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")
    total = sum(len(u.get("words", [])) for u in units)
    print(f"Всего слов в seed: {total} -> {args.out}")

    if args.push:
        import httpx
        r = httpx.post(f"{args.push}/auth/login", data={"username": args.user, "password": args.password})
        r.raise_for_status()
        token = r.json()["access_token"]
        r = httpx.post(f"{args.push}/admin/import_units", json=payload,
                       headers={"Authorization": f"Bearer {token}"}, timeout=120)
        r.raise_for_status()
        print("Импорт:", r.json())


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
